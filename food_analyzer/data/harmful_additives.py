def find_additives_in_text(text: str) -> list:
    """
    Търси E-номера в даден текст.
    Връща списък с намерени вредни добавки.
    """
    found = []
    text_upper = text.upper()
    
    for code, data in HARMFUL_ADDITIVES.items():
        # Търси E102, E-102, e102 и подобни варианти
        variants = [
            code,
            code.replace("E", "E-"),
            code.lower(),
            code.replace("E", "E-").lower()
        ]
        if any(v in text_upper for v in [code, code.replace("E", "E-")]):
            found.append({"code": code, **data})
    
    return found


def get_overall_risk_score(additives: list) -> dict:
    """
    Изчислява общата оценка на риска от намерените добавки.
    """
    if not additives:
        return {"score": 0, "label": "✅ Без известни вредни добавки", "color": "#4CAF50"}
    
    max_score = max(a["risk_score"] for a in additives)
    avg_score = sum(a["risk_score"] for a in additives) / len(additives)
    combined = (max_score * 0.6) + (avg_score * 0.4)
    
    if combined >= 7:
        return {"score": combined, "label": "⛔ Много вредни добавки", "color": "#FF3B30"}
    elif combined >= 5:
        return {"score": combined, "label": "🔴 Вредни добавки", "color": "#FF6B35"}
    elif combined >= 3:
        return {"score": combined, "label": "🟡 Умерено вредни добавки", "color": "#FF9F1C"}
    else:
        return {"score": combined, "label": "🟢 Ниско рискови добавки", "color": "#4CAF50"}
